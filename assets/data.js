/** 把行业产品集内的智能体展开为统一结构：{ id, name, ..., ownerSet } */
function buildVerticalAgents() {
  const out = [];
  INDUSTRY_SETS.forEach((set) => {
    (set.agentRefs || []).forEach((refId) => {
      const base = GENERAL_AGENTS.find((a) => a.id === refId);
      if (base) out.push({ ...base, ownerSet: set.id, reused: true });
    });
    (set.agents || []).forEach((a) => out.push({ ...a, ownerSet: set.id, reused: false }));
  });
  return out;
}

const ALL_VERTICAL = buildVerticalAgents();
const ALL_AGENTS = [...ALL_GENERAL, ...ALL_VERTICAL];

