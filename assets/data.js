function membershipsOf(agentId) {
  const list = [];
  if (GENERAL_AGENTS.some((a) => a.id === agentId)) list.push({ id: "general", name: "通用智能体体系" });
  INDUSTRY_SETS.forEach((s) => {
    const has =
      (s.agentRefs || []).includes(agentId) || (s.agents || []).some((a) => a.id === agentId);
    if (has) list.push({ id: s.id, name: s.setName });
  });
  return list;
}

